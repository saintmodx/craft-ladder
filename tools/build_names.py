"""Item and recipe names in another language, for Craft Ladder's own language setting.

    python -I tools/build_names.py ruRU

The names the addon shows come from the game client, so they are already in its language. This file is for the
other case: the addon set to a language the client doesn't speak (a Russian player on an English client). It holds
only the ids Craft Ladder's data already names, from the same build the data was made from (wago.tools, the
client's own tables: ItemSparse for items, SpellName for recipes).

NPC and quest names are not here: no public source has them in another language (the client's Creature table
holds a couple of hundred rows, and QuestV2 has no title at all).
"""
import argparse
import pathlib
import re
import sys

TOOLS = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(TOOLS))
from build_data import lua  # noqa: E402
import wago  # noqa: E402

DATA = TOOLS.parent / "CraftLadder" / "Data"
OUT = DATA / "Names_%s.lua"
BLOCK = re.compile(r"\n  (items|recipes) = \{(.*?)\n  \}", re.S)


def wanted():
    """The ids the data names: items (its `items` table) and recipes (the spells of its `recipes` table)."""
    items, spells = set(), set()
    for f in sorted(DATA.glob("*.lua")):
        if f.name.startswith("Names_"):
            continue
        text = f.read_text(encoding="utf-8")
        for block, body in BLOCK.findall(text):
            ids = (int(x) for x in re.findall(r"\[(\d+)\]", body))
            (items if block == "items" else spells).update(ids)
    return items, spells


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("locale", help="the game's code for it: ruRU, deDE, frFR, ...")
    ap.add_argument("--refresh", action="store_true", help="download the tables again")
    args = ap.parse_args()

    build = wago.latest_build()
    items, spells = wanted()
    item_names = {}
    for row in wago.table("ItemSparse", build, args.refresh, args.locale):
        i = int(row["ID"])
        if i in items and row["Display_lang"]:
            item_names[i] = row["Display_lang"]
    spell_names = {}
    for row in wago.table("SpellName", build, args.refresh, args.locale):
        i = int(row["ID"])
        if i in spells and row["Name_lang"]:
            spell_names[i] = row["Name_lang"]

    out = OUT.as_posix() % args.locale
    lines = [
        "-- Craft Ladder: item and recipe names in %s, for the language setting." % args.locale,
        "-- GENERATED by tools/build_names.py %s - don't edit by hand; fix the builder and rebuild." % args.locale,
        "-- From the Forever client's tables (build %s): ItemSparse and SpellName. The game's own names come" % build,
        "-- first; these are for a client that speaks another language. NPC and quest names have no source.",
        "local _, ns = ...",
        "",
        "ns.Names = ns.Names or {}",
        "ns.Names.%s = {" % args.locale,
        "  items = {",
    ]
    for i in sorted(item_names):
        lines.append("    [%d] = %s," % (i, lua(item_names[i])))
    lines.append("  },")
    lines.append("  recipes = {")
    for i in sorted(spell_names):
        lines.append("    [%d] = %s," % (i, lua(spell_names[i])))
    lines.append("  },")
    lines.append("}")
    text = "\r\n".join(lines) + "\r\n"
    pathlib.Path(out).write_text(text, encoding="utf-8", newline="")
    print("Names_%s.lua: %d of %d items, %d of %d recipes, %d KB, Forever build %s"
          % (args.locale, len(item_names), len(items), len(spell_names), len(spells),
             len(text.encode("utf-8")) / 1024, build))


main()
